import argparse
import os
import tempfile
import tomllib
from pathlib import Path
import numpy as np
from scipy.linalg import solve_continuous_are

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG = ROOT / "tools/control/configs/single.toml"
DEFAULT_OUTPUT = ROOT / "constants/lqr_gains.inc"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def load_config(path):
    with path.open("rb") as file:
        config = tomllib.load(file)

    for section in ("plant", "weights", "validation"):
        for key, value in config[section].items():
            require(
                np.isfinite(value) and value > 0, f"Invalid parameter: {section}.{key}"
            )

    return config


def build_system(plant):
    M = plant["M"]
    m = plant["m"]
    l = plant["l"]
    g = plant["g"]

    A = np.array(
        [
            [0, 0, 1, 0],
            [0, 0, 0, 1],
            [0, -m * g / M, 0, 0],
            [0, (M + m) * g / (M * l), 0, 0],
        ],
        dtype=float,
    )

    B = np.array(
        [
            [0],
            [0],
            [1 / M],
            [-1 / (M * l)],
        ],
        dtype=float,
    )

    return A, B


def build_weights(weights):
    Q = np.diag(
        [
            weights["x"],
            weights["theta"],
            weights["v"],
            weights["omega"],
        ]
    )

    R = np.array([[weights["force"]]])

    return Q, R


def synthesize(A, B, Q, R):
    P = solve_continuous_are(A, B, Q, R)
    K = np.linalg.solve(R, B.T @ P)

    return P, K


def validate(A, B, Q, R, P, K, config):
    C = np.hstack(
        [
            B,
            A @ B,
            A @ A @ B,
            A @ A @ A @ B,
        ]
    )

    require(np.linalg.matrix_rank(C) == A.shape[0], "System is not controllable")

    residual = A.T @ P + P @ A - P @ B @ K + Q
    residual_norm = np.linalg.norm(residual, ord="fro")

    require(
        residual_norm < config["residual_tolerance"],
        "Riccati residual exceeds tolerance",
    )

    require(
        np.allclose(P, P.T, atol=config["symmetry_tolerance"], rtol=0),
        "P is not symmetric",
    )

    p_eigenvalues = np.linalg.eigvalsh(P)

    require(np.all(p_eigenvalues > 0), "P is not positive definite")

    poles = np.linalg.eigvals(A - B @ K)

    require(np.all(poles.real < 0), "Closed-loop system is unstable")

    # Independent analytical check for the single pendulum
    expected_kx = -np.sqrt(Q[0, 0] / R[0, 0])

    require(
        np.isclose(K[0, 0], expected_kx, rtol=1e-8, atol=1e-10),
        "Cart position gain fails analytical check",
    )

    print("All LQR validation checks passed.")
    print(f"Riccati residual: {residual_norm:.6e}")
    print(f"P eigenvalues:    {p_eigenvalues}")
    print(f"Open-loop poles:  {np.linalg.eigvals(A)}")
    print(f"Closed-loop poles:{poles}")
    print(f"Gains:            {K.ravel()}")


def export_gains(path, plant, Q, R, K):
    kx, ktheta, kv, komega = K.ravel()
    qx, qt, qv, qw = Q.diagonal()

    content = f"""/* Generated by tools/control/lqr.py
 * Q = diag({qx}, {qt}, {qv}, {qw})
 * R = {R[0, 0]}
 * M = {plant["M"]}, m = {plant["m"]},
 * l = {plant["l"]}, g = {plant["g"]}
 */

.kx     = REAL({kx:.17e}),
.ktheta = REAL({ktheta:.17e}),
.kv     = REAL({kv:.17e}),
.komega = REAL({komega:.17e}),
"""

    path.parent.mkdir(parents=True, exist_ok=True)

    # atomically replace the previous generated file.
    with tempfile.NamedTemporaryFile(
        mode="w", dir=path.parent, delete=False, encoding="utf-8"
    ) as file:
        temporary = Path(file.name)

    try:
        temporary.write_text(content, encoding="utf-8")
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)

    print(f"Exported gains to {path}")


def main():
    parser = argparse.ArgumentParser(description="Pendulab LQR synthesis tool")

    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)

    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)

    parser.add_argument("--check-only", action="store_true")

    parser.add_argument("--verbose", action="store_true")

    args = parser.parse_args()
    config = load_config(args.config)

    A, B = build_system(config["plant"])
    Q, R = build_weights(config["weights"])
    P, K = synthesize(A, B, Q, R)

    if args.verbose:
        for name, matrix in [
            ("A", A),
            ("B", B),
            ("Q", Q),
            ("R", R),
            ("P", P),
            ("K", K),
        ]:
            print(f"{name}:\n{matrix}\n")

    validate(A, B, Q, R, P, K, config["validation"])

    if not args.check_only:
        export_gains(args.output, config["plant"], Q, R, K)


if __name__ == "__main__":
    main()
