import numpy as np
from scipy.linalg import solve_continuous_are
from pathlib import Path
import sys

"""
    System parameters 
"""

M = 0.5  # kg
m = 0.1  # kg
l = 0.3  # m
g = 9.81  # m/s^2

cart_disp = 0.2  # m
angular_disp = 0.1  # rad
cart_vel = 1  # m/s
angular_vel = 2  # rad/s
control_F = 10  # N

cart_disp_w = 25
angular_disp_w = 100
cart_vel_w = 1
angular_vel_w = 0.25
control_F_w = 0.01


"""
    Evaluation
"""

a_32 = (-m * g) / (M)
a_42 = (M + m) * g / (M * l)

b_3 = 1 / M
b_4 = -1 / (M * l)


A = np.array(
    [
        [0, 0, 1, 0],
        [0, 0, 0, 1],
        [0, a_32, 0, 0],
        [0, a_42, 0, 0],
    ]
)

B = np.array([[0], [0], [b_3], [b_4]])

Q = np.diag([cart_disp_w, angular_disp_w, cart_vel_w, angular_vel_w])
R = np.array([[0.01]])

P = solve_continuous_are(A, B, Q, R)
K = np.linalg.solve(R, B.T @ P)

residual = A.T @ P + P @ A - P @ B @ K + Q


assert np.linalg.norm(residual, ord="fro") < 1e-8, "Riccati residual exceeds tolerance"

# symmetry
assert np.allclose(P, P.T, atol=1e-10, rtol=0), "P is not symmetric"

# positive definiteness
assert np.all(np.linalg.eigvalsh(P) > 0), "P is not positive definite"

# closed-loop stability
assert np.all(
    np.real(np.linalg.eigvals(A - B @ K)) < 0
), "Closed loop system is unstable"

print("All LQR validation checks passed.")

print(np.linalg.norm(residual, ord="fro"))
print(np.linalg.eigvalsh(P))
print(np.linalg.eigvals(A - B @ K))


kx, ktheta, kv, komega = K.ravel()

gains = f"""/* Auto-generated by tools/control/lqr.py. Do not edit. */

.kx     = REAL({kx}),
.ktheta = REAL({ktheta}),
.kv     = REAL({kv}),
.komega = REAL({komega}),
"""


ROOT = Path(__file__).resolve().parents[2]
INC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "constants/lqr_gains.inc"

with open(INC, "w+") as lqr_gains:
    lqr_gains.write(gains)
